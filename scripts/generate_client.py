"""Generate types from the currently implemented contract; no network/dependencies."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def type_of(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(x, ensure_ascii=False) for x in s["enum"])
    for key in ["anyOf", "oneOf", "allOf"]:
        if key in s:
            return "(" + (" & " if key == "allOf" else " | ").join(type_of(x) for x in s[key]) + ")"
    t = s.get("type")
    if t == "array":
        return f"Array<{type_of(s['items'])}>"
    if t == "object" or "properties" in s:
        if not s.get('properties') and isinstance(s.get('additionalProperties'), dict):
            return f"Record<string, {type_of(s['additionalProperties'])}>"
        required = s.get("required", [])
        return "{ " + " ".join(f"{json.dumps(k)}{'' if k in required else '?'}: {type_of(v)};" for k, v in s.get("properties", {}).items()) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


# Stable application response names survive a fresh export of generic envelopes.
RESPONSE_ALIASES = {'SessionResponse': 'Envelope_Session_', 'ProviderListResponse': 'Envelope_Page_Provider__', 'InstrumentListResponse': 'Envelope_Page_Instrument__', 'EvidenceVersionResponse': 'Envelope_EvidenceVersion_', 'EvidenceVersionListResponse': 'Envelope_Page_EvidenceVersion__', 'SnapshotResponse': 'Envelope_Snapshot_', 'SnapshotListResponse': 'Envelope_Page_Snapshot__', 'CalendarVersionResponse': 'Envelope_CalendarVersion_', 'CalendarVersionListResponse': 'Envelope_Page_CalendarVersion__', 'CalendarLookupResponse': 'Envelope_CalendarLookup_', 'SourceHealthListResponse': 'Envelope_Page_SourceHealth__', 'JobReceiptResponse': 'Envelope_JobReceipt_', 'DocumentResponse': 'Envelope_Document_', 'DocumentListResponse': 'Envelope_Page_Document__', 'RevisionResponse': 'Envelope_Revision_', 'RevisionSummaryListResponse': 'Envelope_Page_RevisionSummary__', 'ObservationResponse': 'Envelope_Observation_', 'ObservationListResponse': 'Envelope_Page_Observation__', 'ValidationResponse': 'Envelope_Validation_', 'ValidationListResponse': 'Envelope_Page_Validation__', 'ReviewArchiveResponse': 'Envelope_ReviewArchive_', 'ReviewArchiveListResponse': 'Envelope_Page_ArchiveSummary__', 'RuntimeSourceListResponse': 'Envelope_SourceIndex_', 'RuntimeSourceResponse': 'Envelope_RuntimeSource_', 'CollectionJobResponse': 'Envelope_CollectionJobReceipt_', 'FetchRunListResponse': 'Envelope_Page_FetchRun__', 'MarketQuoteResponse': 'Envelope_QuoteBatch_', 'DatasetListResponse': 'Envelope_DatasetList_', 'NewsListResponse': 'Envelope_NewsList_', 'BarSeriesResponse': 'Envelope_BarSeries_', 'DataCoverageResponse': 'Envelope_DataCoverage_', 'WatchlistResponse': 'Envelope_WatchlistView_', 'TradingDatasetResponse': 'Envelope_TradingDatasetList_', 'WorkbenchResponse': 'Envelope_WorkbenchView_'}

def generate():
    schema = json.loads((ROOT / "contracts/openapi.p2.json").read_text(encoding="utf-8"))
    generated = "// Generated by scripts/generate_client.py; do not edit.\n" + "\n".join(
        f"export type {name} = {type_of(s)};" for name, s in schema["components"]["schemas"].items()
    ) + "\n"
    components = schema["components"]["schemas"]
    return generated + "".join(f"export type {alias} = {target};\n" for alias, target in RESPONSE_ALIASES.items() if alias not in components and target in components)


if __name__ == "__main__":
    target = ROOT / "frontend/src/generated/schema.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate(), encoding="utf-8", newline="\n")
